package com.google.common.geometry.benchmarks;

import static com.google.common.collect.Iterables.size;
import static com.google.common.collect.Iterators.size;

import com.google.common.collect.ImmutableList;
import com.google.common.geometry.S1Angle;
import com.google.common.geometry.S2Cap;
import com.google.common.geometry.S2CellId;
import com.google.common.geometry.S2CellUnion;
import com.google.common.geometry.S2ClipQuery;
import com.google.common.geometry.S2LatLng;
import com.google.common.geometry.S2LatLngRect;
import com.google.common.geometry.S2Loop;
import com.google.common.geometry.S2Point;
import com.google.common.geometry.S2Polyline;
import com.google.common.geometry.S2RegionCoverer;
import com.google.common.geometry.S2ShapeIndex;
import com.google.common.geometry.S2ShapeUtil;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.logging.Logger;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Level;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;

/**
 * Benchmark for {@link S2ClipQuery}.
 *
 * <p>The test data is generated to have a specific density of edges. For single datasets (POINTS,
 * LINES, etc.), the target is 102400 edges total. For MIX, the edges are divided into types: 20480
 * edges for points, 6826 for lines, 5120 for buildings, 4 for postal areas, and 1 for admin areas,
 * totaling 102400 edges.
 *
 * <p>The clip regions are generated by recursively subdividing the bounding box of the data. The
 * scaling of object counts by object area ensures that even at the deepest level (depth 4), the
 * clip region still selects a reasonable number of edges (target > 100, typically 500-1000),
 * preventing the benchmark from measuring empty queries.
 */
@State(Scope.Thread)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.MICROSECONDS)
@Warmup(iterations = 5, time = 50, timeUnit = TimeUnit.MILLISECONDS)
@Measurement(iterations = 5, time = 50, timeUnit = TimeUnit.MILLISECONDS)
@Fork(1)
public class S2ClipQueryBenchmark extends S2BenchmarkBaseState {
  private static final Logger logger = Logger.getLogger(S2ClipQueryBenchmark.class.getName());

  public enum Dataset {
    POINTS,
    LINES,
    BUILDINGS,
    POSTAL,
    ADMIN,
    MIX
  }

  @Param({"POINTS", "LINES", "BUILDINGS", "POSTAL", "ADMIN", "MIX"})
  Dataset dataset;

  @Param({"0", "1", "2", "3", "4"})
  int depth;

  S2ShapeIndex index;
  S2Cap dataCap;
  S2LatLngRect dataBound;
  S2ClipQuery query;
  List<S2LatLngRect> clipRects;
  List<S2CellUnion> clipUnions;
  List<List<S2CellId>> clipCellsList;
  List<S2ShapeIndex> clipIndices;
  List<Long> shapeCounts;

  @Setup(Level.Trial)
  @Override
  public void setup() {
    super.setup();
    index = new S2ShapeIndex();
    index.options().setMaxEdgesPerCell(20);
    // Default cap
    dataCap = S2Cap.fromAxisAngle(data.getRandomPoint(), S1Angle.degrees(1));
    dataBound = dataCap.getRectBound();

    // Generate data
    generateData();

    // Find suitable clip regions
    findClipRegions();

    // Create the query object (which triggers building the index).
    query = new S2ClipQuery(index);

    // Precompute other clip representations
    S2RegionCoverer coverer = S2RegionCoverer.DEFAULT;
    clipUnions = new ArrayList<>();
    clipCellsList = new ArrayList<>();
    clipIndices = new ArrayList<>();
    shapeCounts = new ArrayList<>();

    for (S2LatLngRect rect : clipRects) {
      S2CellUnion union = coverer.getCovering(rect);
      clipUnions.add(union);
      clipCellsList.add(union.cellIds());

      // Index the rect
      // Create a polygon that approximates the S2LatLngRect
      S2Loop loop = new S2Loop(ImmutableList.of(
          rect.getVertex(0).toPoint(), rect.getVertex(1).toPoint(),
          rect.getVertex(2).toPoint(), rect.getVertex(3).toPoint()));

      S2ShapeIndex idx = S2ShapeIndex.fromShapes(loop);
      idx.applyUpdates();
      clipIndices.add(idx);

      // Compute counts
      query.clip(rect);
      shapeCounts.add((long) size(query.shapes()));
    }
  }

  private void generateData() {
    switch (dataset) {
      case POINTS -> addPoints(dataCap, 102400);
      // Target 102400 edges total for single datasets.
      // Radius calculated as R_cap * sqrt(edges_per_object / 102400) * 10 to ensure coverage ~ 100.
      case LINES -> addLines(dataCap, 34133, S1Angle.degrees(0.054));
      case BUILDINGS -> addBuildings(dataCap, 25600, S1Angle.degrees(0.063));
      case POSTAL -> addPostal(dataCap, 20, S1Angle.degrees(0.22));
      case ADMIN -> addAdmin(dataCap, 5, S1Angle.degrees(0.44));
      case MIX -> {
        // Target 20480 edges per type (102400 total).
        // Radius calculated as R_cap * sqrt(edges_per_object / 20480) * 10.
        addPoints(dataCap, 20480);
        addLines(dataCap, 6826, S1Angle.degrees(0.12));
        addBuildings(dataCap, 5120, S1Angle.degrees(0.14));
        addPostal(dataCap, 4, S1Angle.degrees(0.5));
        addAdmin(dataCap, 1, S1Angle.degrees(1.0));
      }
    }
  }

  private void addPoints(S2Cap cap, int count) {
    List<S2Point> points = new ArrayList<>();
    for (int i = 0; i < count; i++) {
      points.add(data.samplePoint(cap));
    }
    index.add(S2Point.Shape.fromList(points));
  }

  private void addLines(S2Cap cap, int count, S1Angle radius) {
    for (int i = 0; i < count; i++) {
      S2Point center = data.samplePoint(cap);
      List<S2Point> vertices = new ArrayList<>(
          S2Loop.makeRegularLoop(center, radius, 5).vertices());
      // Open the loop to make a polyline
      vertices.remove(vertices.size() - 1);
      index.add(new S2Polyline(vertices));
    }
  }

  private void addBuildings(S2Cap cap, int count, S1Angle radius) {
    for (int i = 0; i < count; i++) {
      S2Point center = data.samplePoint(cap);
      index.add(S2Loop.makeRegularLoop(center, radius, 4));
    }
  }

  private void addPostal(S2Cap cap, int count, S1Angle radius) {
    for (int i = 0; i < count; i++) {
      S2Point center = data.samplePoint(cap);
      // ~5k vertices
      index.add(data.makeRandomFractal(new S2LatLng(center), radius, 5000).shape());
    }
  }

  private void addAdmin(S2Cap cap, int count, S1Angle radius) {
    for (int i = 0; i < count; i++) {
      S2Point center = data.samplePoint(cap);
      // Large fractal, ~20k vertices
      index.add(data.makeRandomFractal(new S2LatLng(center), radius, 20000).shape());
    }
  }

  private void findClipRegions() {
    clipRects = new ArrayList<>();
    // Start with the full bounds of the index
    // S2ShapeIndex doesn't directly expose bounds, so compute it.
    // For simplicity, we know we generated data in 'cap'.
    // Let's start with the bounding rect of that cap.
    S2LatLngRect currentRect = dataBound;

    S2ClipQuery q = new S2ClipQuery(index);
    long initialTotalEdges = S2ShapeUtil.countEdges(index);

    // Subdivide until result edges < 100
    // Limit depth to avoid infinite loop if data is too dense
    for (int depth = 0; depth < 5; depth++) {
      clipRects.add(currentRect);

      q.clip(currentRect);
      long currentEdges = countEdges(q);

      if (currentEdges < 100) {
        logger.info("Reached small edge count " + currentEdges + " at depth " + depth);
        // Continue adding currentRect to fill up to depth 5 if needed
      }

      // Target for next level
      long targetEdges = initialTotalEdges / (1L << (2 * (depth + 1)));

      // Subdivide: take center quadrant that is closest to target density
      S2LatLng center = currentRect.getCenter();
      S2LatLngRect[] candidates = new S2LatLngRect[4];
      for (int k = 0; k < 4; ++k) {
        candidates[k] = S2LatLngRect.fromPointPair(center, currentRect.getVertex(k));
      }

      S2LatLngRect bestRect = candidates[0];
      long bestDiff = Long.MAX_VALUE;

      for (S2LatLngRect candidate : candidates) {
        q.clip(candidate);
        long edges = countEdges(q);
        long diff = Math.abs(edges - targetEdges);
        if (diff < bestDiff) {
          bestDiff = diff;
          bestRect = candidate;
        }
      }
      currentRect = bestRect;
    }
    // Pad with last rect if needed
    while (clipRects.size() < 5) {
      clipRects.add(clipRects.get(clipRects.size() - 1));
    }
  }

  private long countEdges(S2ClipQuery q) {
    long count = 0;
    for (int id : q.shapes()) {
      count += size(q.edgeIds(id));
    }
    return count;
  }

  @Benchmark
  public void clipLatLngRect(Blackhole bh) {
    query.clip(clipRects.get(depth));
    for (int id : query.shapes()) {
      bh.consume(size(query.edgeIds(id)));
    }
  }

  @Benchmark
  public void clipCellUnion(Blackhole bh) {
    query.clip(clipUnions.get(depth));
    for (int id : query.shapes()) {
      bh.consume(size(query.edgeIds(id)));
    }
  }

  @Benchmark
  public void addClipCellId(Blackhole bh) {
    query.clear();
    for (S2CellId id : clipCellsList.get(depth)) {
      query.addClip(id);
    }
    for (int id : query.shapes()) {
      bh.consume(size(query.edgeIds(id)));
    }
  }

  @Benchmark
  public void clipShapeIndex(Blackhole bh) {
    query.clip(clipIndices.get(depth));
    for (int id : query.shapes()) {
      bh.consume(size(query.edgeIds(id)));
    }
  }

  @Benchmark
  public void iterateShapes(Blackhole bh) {
    query.clip(clipRects.get(depth));
    bh.consume(size(query.shapes()));
    for (int id : query.shapes()) {
      bh.consume(size(query.edgeIds(id)));
    }
  }

  @Benchmark
  public void iterateEdges(Blackhole bh) {
    query.clip(clipRects.get(depth));
    for (int id : query.shapes()) {
      bh.consume(size(query.edgeIds(id)));
    }
  }

  @Benchmark
  public void iterateChains(Blackhole bh) {
    query.clip(clipRects.get(depth));
    for (int id : query.shapes()) {
      for (S2ClipQuery.Chain chain : query.chains(id)) {
        bh.consume(size(chain.offsets()));
      }
    }
  }

  @Benchmark
  public void iterateVertices(Blackhole bh) {
    query.clip(clipRects.get(depth));
    for (int id : query.shapes()) {
      for (S2ClipQuery.Chain chain : query.chains(id)) {
        bh.consume(size(chain.vertices())); // Consumes the iterator
      }
    }
  }
}
